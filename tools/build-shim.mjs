// Builds script.js from index.html and plugin.json.
// script.js is a compatibility shim for NotePlan < 3.21. From 3.21 on, NotePlan loads index.html directly
// (plugin.type: "html"). Edit index.html, app.js and styles.css – never script.js.
// Run from the repo root: node tools/build-shim.mjs
import { readFileSync, writeFileSync } from 'node:fs'

const manifest = JSON.parse(readFileSync('plugin.json', 'utf8'))
const html = readFileSync('index.html', 'utf8')
const cmd = manifest['plugin.commands'][0]
const opts = {
  id: `main:${manifest['plugin.id']}:${cmd.sidebarView.title}`,
  icon: cmd.sidebarView.icon,
  iconColor: cmd.sidebarView.iconColor,
}
const out = `// Auto-generated by tools/build-shim.mjs – do not edit. Edit index.html instead.
// Compatibility shim for NotePlan < 3.21.
globalThis.${cmd.jsFunction} = async function() {
  const html = ${JSON.stringify(html)};
  await HTMLView.showInMainWindow(html, ${JSON.stringify(cmd.sidebarView.title)}, ${JSON.stringify(opts, null, 2).replace(/\n/g, '\n  ')});
};
// Called by NotePlan after the user saves the plugin settings. The view reads
// the settings when it opens, so there is nothing to do here.
globalThis.onSettingsUpdated = async function() {};
`
writeFileSync('script.js', out)
console.log('script.js written (' + out.length + ' bytes)')
